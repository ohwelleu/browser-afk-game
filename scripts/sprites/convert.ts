/**
 * PNG → text sprite converter (step 1: pixels and palette only).
 *
 * Pure functions, no file system access, so tests can feed in-memory PNGs.
 * The CLI (`cli.ts`) does the reading and writing.
 */
import { PNG } from 'pngjs';

/** Palette colour → slot. Must match docs/SPRITES.md and art/afk-palette.gpl. */
export const COLOR_TO_SLOT: Readonly<Record<string, string>> = {
  '#1f1f1f': '#',
  '#ece9e2': 'o',
  '#ff6b00': 'O',
  '#eab308': 'Y',
  '#dc2626': 'R',
  '#7c3aed': 'P',
  '#16a34a': 'G',
  '#2563eb': 'B',
  '#db2777': 'K',
  '#8b5a2b': 'N',
};

/** Marker colours from the palette. Recognised, but markers come in a later step. */
export const MARKERS: Readonly<Record<string, string>> = {
  '#ff00ff': 'anchor',
  '#00ffff': 'hit',
  '#00ff00': 'fx',
};

export type FrameSize = { width: number; height: number };

export type Strip = {
  /** Label used in errors and as the sprite name, e.g. `hero-idle`. */
  label: string;
  width: number;
  height: number;
  frames: string[][];
  /** Milliseconds per frame (Aseprite sheets only; plain PNG strips have none). */
  durations?: number[];
};

/** Parses `32x64` into a frame size. */
export function parseFrameSize(text: string): FrameSize {
  const m = /^(\d+)x(\d+)$/.exec(text.trim());
  if (!m || +m[1] <= 0 || +m[2] <= 0)
    throw new Error(`bad frame size "${text}", expected e.g. 32x64`);
  return { width: +m[1], height: +m[2] };
}

const hex = (r: number, g: number, b: number) =>
  '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');

/**
 * Reads `count` frames of `fw`x`fh` laid out left to right from a decoded PNG
 * and maps each pixel to its palette slot. `where(f)` names frame `f` (0-based)
 * in error messages. Bad pixels become `?` and push an error.
 */
export function cutFrames(
  img: PNG,
  fw: number,
  fh: number,
  count: number,
  where: (f: number) => string,
  errors: string[],
): string[][] {
  const frames: string[][] = [];
  for (let f = 0; f < count; f++) {
    const rows: string[] = [];
    for (let y = 0; y < fh; y++) {
      let row = '';
      for (let x = 0; x < fw; x++) {
        const i = (y * img.width + f * fw + x) * 4;
        const [r, g, b, a] = img.data.subarray(i, i + 4);
        const at = `${where(f)} (${x},${y})`;
        const color = hex(r, g, b);
        if (a === 0) {
          row += '.';
        } else if (a !== 255) {
          errors.push(`${at}: ${color} is semi-transparent (alpha ${a}), use 0 or 255`);
          row += '?';
        } else if (COLOR_TO_SLOT[color]) {
          row += COLOR_TO_SLOT[color];
        } else if (MARKERS[color]) {
          errors.push(`${at}: ${color} is a marker (${MARKERS[color]}), not supported yet`);
          row += '?';
        } else {
          errors.push(`${at}: ${color} is not in the palette`);
          row += '?';
        }
      }
      rows.push(row);
    }
    frames.push(rows);
  }
  return frames;
}

/**
 * Cuts a decoded PNG (horizontal strip) into frames of char rows.
 * Without `frame`, the whole image is one frame.
 * Returns the strip and a list of errors (empty = valid).
 */
export function pngToStrip(
  png: Buffer,
  label: string,
  frame?: FrameSize,
): { strip: Strip; errors: string[] } {
  const img = PNG.sync.read(png);
  const fw = frame?.width ?? img.width;
  const fh = frame?.height ?? img.height;
  const strip: Strip = { label, width: fw, height: fh, frames: [] };
  const errors: string[] = [];

  if (img.height !== fh || img.width % fw !== 0) {
    errors.push(
      `${label}: image is ${img.width}x${img.height}, not a horizontal strip of ${fw}x${fh} frames`,
    );
    return { strip, errors };
  }

  strip.frames = cutFrames(img, fw, fh, img.width / fw, (f) => `${label} frame ${f + 1}`, errors);
  return { strip, errors };
}

/** Every strip of one character must use the same frame size. */
export function checkSameSize(strips: Strip[]): string[] {
  const [first, ...rest] = strips;
  return rest
    .filter((s) => s.width !== first.width || s.height !== first.height)
    .map(
      (s) =>
        `${s.label}: frames are ${s.width}x${s.height}, expected ${first.width}x${first.height} like ${first.label}`,
    );
}

/** `hero-idle` → `heroIdle`. */
export const exportName = (label: string) =>
  label.replace(/[-_]+([a-z0-9])/gi, (_, c: string) => c.toUpperCase());

/**
 * `fps` (average, so today's renderer plays the right total length) and the
 * exact per-frame `durations` in ms. Nothing for strips without durations.
 */
function timing(s: Strip): string[] {
  if (!s.durations) return [];
  const total = s.durations.reduce((a, b) => a + b, 0);
  const fps = Math.round(((1000 * s.durations.length) / total) * 100) / 100;
  return [`  fps: ${fps},`, `  durations: [${s.durations.join(', ')}],`];
}

/** Generated TS module for one character (all its strips). */
export function renderModule(strips: Strip[], sources: string[]): string {
  const out = [
    '// Generated by `npm run sprites`, do not edit.',
    `// Source: ${sources.join(', ')}`,
    "import type { SpriteDef } from '../types';",
  ];
  for (const s of strips) {
    out.push(
      '',
      `export const ${exportName(s.label)}: SpriteDef = {`,
      `  name: '${s.label}',`,
      `  width: ${s.width},`,
      `  height: ${s.height},`,
      ...timing(s),
      '  frames: [',
      ...s.frames.flatMap((f) => ['    [', ...f.map((row) => `      '${row}',`), '    ],']),
      '  ],',
      '};',
    );
  }
  return out.join('\n') + '\n';
}
